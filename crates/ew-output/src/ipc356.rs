//! IPC-D-356A netlists for the electrical test of bare boards (flying
//! probe or bed of nails): one fixed-width record per pad and via with its
//! net, position, size, drill and solder mask access.
//!
//! The layout follows KiCad's writer, which board makers accept: units are
//! 0.0001 inch (`UNITS CUST 0`), coordinates are relative to the board
//! origin with y up, and net names longer than 14 characters get aliases.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use ew_model::layer::{Layer, Side};
use ew_model::pcb::{PadKind, PadShape, Pcb};
use ew_pcb::geom::V;
use ew_pcb::items::footprint_xform;

use crate::art::pad_on;

/// Tenths of a thousandth of an inch.
fn units(nm: f64) -> i64 {
    (nm / 2_540.0).round() as i64
}

struct Record {
    code: u16,
    net: String,
    designator: String,
    pin: String,
    midpoint: bool,
    drill: Option<(i64, bool)>,
    access: u8,
    at: (i64, i64),
    size: (i64, i64),
    rotation: i64,
    mask: u8,
}

fn truncate(text: &str, width: usize) -> String {
    text.chars().take(width).collect()
}

/// Writes the IPC-D-356A netlist of a board.
#[must_use]
#[allow(clippy::too_many_lines, reason = "vias, pads, then the records")]
pub fn netlist(pcb: &Pcb, tented_vias: bool, version: &str) -> String {
    let copper = pcb.stackup.copper_count().max(1);
    let names: BTreeMap<_, _> = pcb.nets.iter().map(|n| (n.id, n.name.as_str())).collect();
    let origin = V::of(pcb.origin);
    let mut aliases: Vec<String> = Vec::new();
    let mut net_name = |net: Option<ew_model::id::Id>| -> String {
        let name = net.and_then(|id| names.get(&id).copied()).unwrap_or("N/C");
        let name = if name.is_empty() { "N/C" } else { name };
        if name.chars().count() <= 14 {
            return name.to_owned();
        }
        let index = aliases.iter().position(|a| a == name).unwrap_or_else(|| {
            aliases.push(name.to_owned());
            aliases.len() - 1
        });
        format!("NNAME{}", index + 1)
    };
    let mut records = Vec::new();
    for via in &pcb.vias {
        let at = V::of(via.at).sub(origin);
        records.push(Record {
            code: 317,
            net: net_name(via.net),
            designator: "VIA".to_owned(),
            pin: String::new(),
            midpoint: true,
            drill: Some((units(via.drill as f64), true)),
            access: 0,
            at: (units(at.x), units(at.y)),
            size: (units(via.diameter as f64), 0),
            rotation: 0,
            mask: if tented_vias { 3 } else { 0 },
        });
    }
    for fp in &pcb.footprints {
        let xf = footprint_xform(fp);
        for pad in &fp.pads {
            let on_top = pad_on(fp, pad, Layer::TOP_COPPER, copper);
            let on_bottom = pad_on(fp, pad, Layer::BOTTOM_COPPER, copper);
            if !on_top && !on_bottom {
                continue;
            }
            let at = xf.apply(V::of(pad.at)).sub(origin);
            let open_top = pad_on(fp, pad, Layer::SolderMask(Side::Top), copper);
            let open_bottom = pad_on(fp, pad, Layer::SolderMask(Side::Bottom), copper);
            let mask = u8::from(!open_top) + 2 * u8::from(!open_bottom);
            let local = pad.rotation.degrees() + fp.rotation.degrees();
            let local = if fp.side == Side::Bottom {
                fp.rotation.degrees() - pad.rotation.degrees()
            } else {
                local
            };
            let rotation = ((360.0 - local).rem_euclid(360.0)).round() as i64 % 360;
            let size = match pad.shape {
                PadShape::Circle => (units(pad.size.w as f64), 0),
                _ => (units(pad.size.w as f64), units(pad.size.h as f64)),
            };
            let (code, drill, access) = match (pad.drill, pad.kind) {
                (Some(drill), PadKind::NpThroughHole) => {
                    (367, Some((units(drill.diameter as f64), false)), 0)
                }
                (Some(drill), _) => (317, Some((units(drill.diameter as f64), true)), 0),
                (None, _) => (327, None, if on_top { 1 } else { copper }),
            };
            records.push(Record {
                code,
                net: net_name(pad.net),
                designator: fp.designator.clone(),
                pin: pad.number.clone(),
                midpoint: false,
                drill,
                access,
                at: (units(at.x), units(at.y)),
                size,
                rotation,
                mask,
            });
        }
    }
    let mut out = String::new();
    let _ = writeln!(out, "C  IPC-D-356A netlist of {}", pcb.name);
    let _ = writeln!(out, "C  Generated by ElectronicWerk {version}");
    out.push_str("P  CODE 00\nP  UNITS CUST 0\nP  arrayDim   N\n");
    for (i, name) in aliases.iter().enumerate() {
        let _ = writeln!(out, "P  NNAME{:<5} {name}", i + 1);
    }
    for r in &records {
        let _ = write!(
            out,
            "{:03}{:<14}   {:<6}{}{:<4}{}",
            r.code,
            truncate(&r.net, 14),
            truncate(&r.designator, 6),
            if r.pin.is_empty() { ' ' } else { '-' },
            truncate(&r.pin, 4),
            if r.midpoint { 'M' } else { ' ' }
        );
        match r.drill {
            Some((d, plated)) => {
                let _ = write!(
                    out,
                    "D{:04}{}",
                    d.clamp(0, 9999),
                    if plated { 'P' } else { 'U' }
                );
            }
            None => out.push_str("      "),
        }
        let _ = writeln!(
            out,
            "A{:02}X{:+07}Y{:+07}X{:04}Y{:04}R{:03}S{}",
            r.access,
            r.at.0.clamp(-999_999, 999_999),
            r.at.1.clamp(-999_999, 999_999),
            r.size.0.clamp(0, 9999),
            r.size.1.clamp(0, 9999),
            r.rotation,
            r.mask
        );
    }
    out.push_str("999\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn units_are_tenths_of_mils() {
        assert_eq!(units(400_000.0), 157);
        assert_eq!(units(25_000_000.0), 9843);
    }
}
